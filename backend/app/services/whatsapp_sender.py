"""WhatsApp outbound helpers — wrap the Twilio REST API.

Two distinct return paths for outbound messages exist:

1. SYNCHRONOUS reply via TwiML — the webhook returns a <Response><Message>
   ...</Message></Response> body. Twilio sends that as the reply to the
   inbound message. Faster (one round-trip), but limited to one reply per
   inbound, and TwiML only supports Body (no content_sid).

2. ASYNCHRONOUS reply via the REST API — POST to messages.create() with
   the customer's number as 'to'. Used when:
     - The reply contains a Content Template (TwiML can't carry one)
     - We need to send multiple messages in response to one inbound
     - The reply is generated by a Celery worker (LLM safety valve path)
     - The reply is a follow-up triggered by a non-WhatsApp event (e.g.
       owner approves a registration in the dashboard)

This module handles path 2. Path 1 is string building in webhooks.py.

We log every outbound message to conversation_messages here so the audit
trail captures both sync and async sends. The TwiML synchronous path
must log separately — different code path.

Three outbound shapes exist:
  send_text     — plain text body (free-form, in-session)
  send_template — Content Template (interactive buttons via Content API);
                  callers pass the ContentSid + variable substitutions.
  send_reply / send_replies — dispatch on a Reply object's shape and
                  route to send_text or send_template accordingly. The
                  webhook and Celery callers use these so they don't
                  branch on shape themselves.
"""

import json
import logging

from sqlalchemy.orm import Session
from twilio.base.exceptions import TwilioRestException

from app.core.config import settings
from app.core.twilio_client import get_twilio_client
from app.services.conversation_log import log_outbound_message
from app.services.reply import Reply


logger = logging.getLogger(__name__)


def _normalize_whatsapp_address(phone: str) -> str:
    """Ensure the address has the whatsapp: scheme prefix."""
    return phone if phone.startswith("whatsapp:") else f"whatsapp:{phone}"


def send_text(
        db: Session,
        *,
        conversation_id,
        to_phone: str,
        body: str
) -> str | None:
    """Send a plain Whatsapp text message to customer"""
    twilio = get_twilio_client()
    to_address = _normalize_whatsapp_address(to_phone)

    try:
        message = twilio.messages.create(
            from_=settings.TWILIO_WHATSAPP_FROM,
            to=to_address,
            body=body
        )
        sid = message.sid
        logger.info("Outbound WhatsApp sent: to=%s sid=%s", to_phone, sid)
    except TwilioRestException as e:
        # Common causes: customer hasn't joined the sandbox, customer is
        # outside the 24-hour service window, our number is rate-limited.
        # We log and return None — the caller decides how to proceed.
        logger.error(
            "Twilio send failed: to=%s code=%s msg=%s",
            to_phone, e.code, e.msg
        )
        sid = None

    # Always log the attempt to conversation_messages, even on failure —
    # the audit trail should show "we tried to send X" regardless of
    # delivery success.
    log_outbound_message(
        db,
        conversation_id=conversation_id,
        body=body,
        twilio_sid=sid
    )

    return sid


def send_template(
        db: Session,
        *,
        conversation_id,
        to_phone: str,
        content_sid: str,
        content_variables: dict[str, str] | None = None,
        log_body: str | None = None,
) -> str | None:
    """Send a WhatsApp Content Template message (interactive buttons).

    Mirrors send_text but uses Twilio's content_sid + content_variables
    parameters instead of a free-form body. The message body and button
    layout are baked into the template at creation time (see
    scripts/bootstrap_content_templates.py); content_variables fills the
    {{1}}, {{2}}, ... placeholders Twilio substitutes at send time.

    Args:
        content_sid: The Twilio ContentSid (HX...) for the template.
        content_variables: Optional dict mapping placeholder index
            (string keys "1", "2", ...) to substitution values. Omit
            entirely if the template has no variables. The Twilio REST
            API expects this serialized as a JSON string; we do that
            here so callers pass a natural Python dict.
        log_body: Optional human-readable text to record in the audit
            log. Defaults to a structured "[template:HX...] vars=..."
            string so the audit trail is still grep-able even when
            callers don't supply one — but callers that have meaningful
            preview text (the template body with variables inlined)
            should pass it so the admin transcript viewer renders
            something readable.

    Returns:
        The Twilio Message SID on success, or None if the send failed.
        The attempt is always logged to conversation_messages.
    """
    twilio = get_twilio_client()
    to_address = _normalize_whatsapp_address(to_phone)

    create_kwargs: dict[str, str] = {
        "from_": settings.TWILIO_WHATSAPP_FROM,
        "to": to_address,
        "content_sid": content_sid,
    }
    if content_variables:
        # Twilio's REST API expects ContentVariables as a JSON-encoded
        # string. The SDK passes the value through as-is, so we must
        # serialize here — passing a dict would be silently coerced to
        # str(dict) (Python repr with single quotes), which Twilio
        # rejects as malformed JSON.
        create_kwargs["content_variables"] = json.dumps(content_variables)

    try:
        message = twilio.messages.create(**create_kwargs)
        sid = message.sid
        logger.info(
            "Outbound WhatsApp template sent: to=%s content_sid=%s sid=%s",
            to_phone, content_sid, sid
        )
    except TwilioRestException as e:
        logger.error(
            "Twilio template send failed: to=%s content_sid=%s code=%s msg=%s",
            to_phone, content_sid, e.code, e.msg
        )
        sid = None

    # Build the audit log body. If the caller didn't supply one, fall
    # back to a structured representation so we can still trace what
    # was sent.
    if log_body is None:
        log_body = f"[template:{content_sid}]"
        if content_variables:
            log_body = f"{log_body} vars={content_variables}"

    log_outbound_message(
        db,
        conversation_id=conversation_id,
        body=log_body,
        twilio_sid=sid
    )

    return sid


def send_reply(
        db: Session,
        *,
        conversation_id,
        to_phone: str,
        reply: Reply,
) -> str | None:
    """Send a single Reply via the appropriate Twilio path.

    Dispatches to send_text or send_template based on the Reply's shape.
    Callers should use this (or send_replies for lists) rather than
    branching on Reply shape themselves.
    """
    if reply.is_template:
        # is_template guarantees content_sid is set; the cast quiets
        # static type checkers without a runtime cost.
        assert reply.content_sid is not None
        return send_template(
            db,
            conversation_id=conversation_id,
            to_phone=to_phone,
            content_sid=reply.content_sid,
            content_variables=reply.content_variables,
            log_body=reply.log_body,
        )
    # XOR invariant in Reply.__post_init__ guarantees body is set when
    # is_template is False.
    assert reply.body is not None
    return send_text(
        db,
        conversation_id=conversation_id,
        to_phone=to_phone,
        body=reply.body,
    )


def send_replies(
        db: Session,
        *,
        conversation_id,
        to_phone: str,
        replies: list[Reply],
) -> list[str | None]:
    """Send multiple Replies in order. Returns list of SIDs (None for failures).

    Sends sequentially via separate REST API calls. Twilio queues
    messages to the same recipient and delivers them in submission order
    in practice; strict ordering isn't formally guaranteed, but for our
    short [text, nav-template] sequences this works reliably.
    """
    return [
        send_reply(
            db,
            conversation_id=conversation_id,
            to_phone=to_phone,
            reply=r,
        )
        for r in replies
    ]
