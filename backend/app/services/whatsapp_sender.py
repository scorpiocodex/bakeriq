"""WhatsApp outbound helpers — wrap the Twilio REST API.

Two distinct return paths for outbound messages exist:

1. SYNCHRONOUS reply via TwiML — the webhook returns a <Response><Message>
   ...</Message></Response> body. Twilio sends that as the reply to the
   inbound message. Faster (one round-trip), but limited to one reply per
   inbound.

2. ASYNCHRONOUS reply via the REST API — POST to messages.create() with
   the customer's number as 'to'. Used when:
     - We need to send multiple messages in response to one inbound
     - The reply is generated by a Celery worker (LLM safety valve path)
     - The reply is a follow-up triggered by a non-WhatsApp event (e.g.
       owner approves a registration in the dashboard)

This module handles path 2. Path 1 is just string building in webhooks.py.

We log every outbound message to conversation_messages here so the audit
trail captures both sync and async sends. The TwiML synchronous path
must log separately — different code path.
"""

import logging

from sqlalchemy.orm import Session
from twilio.base.exceptions import TwilioRestException

from app.core.config import settings
from app.core.twilio_client import get_twilio_client
from app.services.conversation_log import log_outbound_message


logger = logging.getLogger(__name__)


def send_text(
        db: Session,
        *,
        conversation_id,
        to_phone: str,
        body: str
) -> str | None:
    """Send a plain Whatsapp text message to customer"""
    twilio = get_twilio_client()
    to_address = to_phone if to_phone.startswith("whatsapp:") else f"whatsapp:{to_phone}"

    try:
        message = twilio.messages.create(
            from_=settings.TWILIO_WHATSAPP_FROM,
            to=to_address,
            body=body
        )
        sid = message.sid
        logger.info("Outbound WhatsApp sent: to=%s sid=%s", to_phone, sid)
    except TwilioRestException as e:
        # Common causes: customer hasn't joined the sandbox, customer is
        # outside the 24-hour service window, our number is rate-limited.
        # We log and return None — the caller decides how to proceed.
        logger.error(
            "Twilio send failed: to=%s code=%s msg=%s",
            to_phone, e.code, e.msg
        )
        sid = None

    # Always log the attempt to conversation_messages, even on failure —
    # the audit trail should show "we tried to send X" regardless of
    # delivery success.
    log_outbound_message(
        db,
        conversation_id=conversation_id,
        body=body,
        twilio_sid=sid
    )

    return sid
